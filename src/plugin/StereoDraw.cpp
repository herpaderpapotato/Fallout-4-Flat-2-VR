        // ---- per-eye motion vectors: the pass (constants: BuildMvFix) ---------------------------------------------
        constexpr const char* kMvFixHlsl = R"(
cbuffer MvFix : register(b0)
{
    row_major float4x4 invEye[2];
    row_major float4x4 eyeP[2];
    row_major float4x4 monoP;
    row_major float4x4 invMonoP;
    row_major float4x4 invEye1[2];
    row_major float4x4 eyeP1[2];
    row_major float4x4 monoP1;
    row_major float4x4 invMonoP1;
    row_major float4x4 prevFromCur;
    float4 size;
    float4 misc;
};
Texture2D<float2> tMv : register(t0);
Texture2D<float> tDepth : register(t1);

float4 vs(uint id : SV_VertexID) : SV_Position
{
    float2 p = float2((id << 1) & 2, id & 2);
    return float4(p * float2(2, -2) + float2(-1, 1), 0, 1);
}

float2 ToUv(float4 c)
{
    float2 n = c.xy / c.w;
    return float2(n.x * 0.5 + 0.5, 0.5 - n.y * 0.5);
}

float2 ps(float4 pos : SV_Position) : SV_Target
{
    int2   ip = int2(pos.xy);
    float2 mv = tMv.Load(int3(ip, 0)) * misc.y;  // -> uv_prev - uv_cur
    float  d = tDepth.Load(int3(ip, 0));
    uint   e = pos.x >= size.z ? 1 : 0;
    float2 uv = pos.xy / size.xy;
    float2 ndc = float2(uv.x * 2 - 1, 1 - uv.y * 2);
    bool   fp = d <= 0.01 && misc.z > 0.5;
    float  zn = d <= 0.01 ? d * 100 : d * 1.01 - 0.01;
    float4 v = mul(float4(ndc, zn, 1), fp ? invEye1[e] : invEye[e]);
    v.xyz /= v.w;
    float2 uvm = ToUv(mul(float4(v.xyz, 1), fp ? monoP1 : monoP));
    float2 uvmPrev = uvm + mv;
    float  zPrev = fp ? v.z : mul(float4(v.xyz, 1), prevFromCur).z;
    float4 r = mul(float4(uvmPrev.x * 2 - 1, 1 - uvmPrev.y * 2, 0.5, 1), fp ? invMonoP1 : invMonoP);
    float3 dir = r.xyz / r.w;
    float3 pPrev = dir * (zPrev / dir.z);
    float2 uvePrev = ToUv(mul(float4(pPrev, 1), fp ? eyeP1[e] : eyeP[e]));
    float2 uveCur = ToUv(mul(float4(v.xyz, 1), fp ? eyeP1[e] : eyeP[e]));
    float  lo = e * 0.5 + misc.x / size.x, hi = (e + 1) * 0.5 - misc.x / size.x;
    uvePrev.x = clamp(uvePrev.x, lo, hi);
    float2 o = uvePrev - uveCur;
    return all(isfinite(o)) ? o * misc.y : tMv.Load(int3(ip, 0));
}
)";
