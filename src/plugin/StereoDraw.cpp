        g_ctx = a_immediate;
        bool ok = PatchSlot(a_device, slot::kCreateVertexShader, reinterpret_cast<void*>(&HkCreateVS), o_createVS);
        ok = ok && PatchSlot(a_device, slot::kCreateInputLayout, reinterpret_cast<void*>(&HkCreateIL), o_createIL);
        ok = ok && PatchSlot(a_device, slot::kCreatePixelShader, reinterpret_cast<void*>(&HkCreatePS), o_createPS);
