    std::string Command(const std::string& a_verb, const std::string& a_arg)
    {
        Config     c = CurrentConfig();
        const bool on = std::atoi(a_arg.c_str()) != 0;
        if (a_verb == "stereosplit") {
            c.split = on;
        } else if (a_verb == "stereosao") {
            c.saoPerEye = on;
        } else if (a_verb == "stereosaonoise") {
            // SAO RawAO twin (eye-relative noise) on/off (A/B)
            g_saoEyeNoise.store(on);
            return std::format("saoEyeNoise={}", on ? 1 : 0);
        } else if (a_verb == "stereoskipgroups") {
            // measurement: "stereoskipgroups <a> [b]" skips every draw whose VS or PS is from fxp group a/b; "-1" = off
            int a = -1, b = -1;
            std::sscanf(a_arg.c_str(), "%d %d", &a, &b);
            g_skipGroupA.store(a);
            g_skipGroupB.store(b);
            return std::format("skip groups {} {}", a, b);
        } else if (a_verb == "stereomvcheck") {
            g_mvCheck.state = 1;  // render thread picks it up at the next TAA resolve of a stereo frame
            return "armed (log: stereomvcheck line)";
        } else if (a_verb == "stereotaa") {
            // per-eye TAA motion vectors on/off (A/B)
            c.taaPerEye = on;
        } else if (a_verb == "stereotrace") {
            internal::RequestTrace((std::max)(1, std::atoi(a_arg.c_str())));
            return "trace requested (log: stereotrace lines)";
        } else if (a_verb == "stereosetting") {
            const auto sp = a_arg.find(' ');
            return internal::ForceSetting(a_arg.substr(0, sp), sp == std::string::npos ? 1 : std::atoi(a_arg.c_str() + sp + 1));
        } else if (a_verb == "stereopost") {
            // per-eye image-space passes (motion blur, lens flare) on/off (A/B)
            g_postEye.store(on);
            return std::format("postEye={} | draws mb {} flare {} vis {} fail {} ssrTwin {} | pool buffers {}", on ? 1 : 0, g_postDraws[0],
                g_postDraws[1], g_postDraws[2], g_postFail, g_ssrTwinDraws, g_trPoolN);
        } else if (a_verb == "stereosaobias") {
            g_saoMonoBias.store(on);  // 0 = eye-local NDC (session 3), 1 = mono NDC of the direction (asymmetric eyes)
            return std::format("saoMonoBias={}", on ? 1 : 0);
        } else if (a_verb == "stereofar") {
            // eye far plane = x * mono far (StereoMath g_eyeFarScale; 1 = old behaviour)
            if (a_arg.empty()) {
                return std::format("eyeFarScale={}", math::g_eyeFarScale.load());
            }
            c.eyeFarScale = (std::max)(1.0, std::atof(a_arg.c_str()));
        } else if (a_verb == "stereozclamp") {
            c.keepMonoDepthClip = on;  // VS twins keep mono's depth-clip status (A/B)
        } else if (a_verb == "stereocant") {
            double y = 0, p = 0;
            std::sscanf(a_arg.c_str(), "%lf %lf", &y, &p);
            internal::g_cantDeg[0].store(y);
            internal::g_cantDeg[1].store(p);
            return std::format("cant yaw {} pitch {} deg", y, p);
        } else if (a_verb == "stereoscissor") {
            // engine scissor in split draws: 0 intersect as is (old), 1 remap per eye (default), 2 ignore; log = next 64
            if (a_arg == "log") {
                g_scissorLog.store(64);
            } else if (!a_arg.empty()) {
                g_scissorMode.store(std::atoi(a_arg.c_str()));
            }
            return std::format("scissorMode={} split draws with engine scissor {} clipped {} | tan mono {:.6f} {:.6f} {:.6f} {:.6f} eyeL {:.6f} "
                               "{:.6f} {:.6f} {:.6f} eyeR {:.6f} {:.6f} {:.6f} {:.6f} | eyeL pos {:.3f} {:.3f} {:.3f} eyeR pos {:.3f} {:.3f} {:.3f}",
                g_scissorMode.load(), g_scissorDraws, g_scissorClipped, g_monoTan[0], g_monoTan[1], g_monoTan[2], g_monoTan[3], g_eyeTan[0][0],
                g_eyeTan[0][1], g_eyeTan[0][2], g_eyeTan[0][3], g_eyeTan[1][0], g_eyeTan[1][1], g_eyeTan[1][2], g_eyeTan[1][3], g_eyeRel[0].pos[0],
                g_eyeRel[0].pos[1], g_eyeRel[0].pos[2], g_eyeRel[1].pos[0], g_eyeRel[1].pos[1], g_eyeRel[1].pos[2]) +
                   std::format(" | eye fwd in head: L ({:.5f} {:.5f} {:.5f}) R ({:.5f} {:.5f} {:.5f})", g_eyeRel[0].rot[0][2], g_eyeRel[0].rot[1][2],
                       g_eyeRel[0].rot[2][2], g_eyeRel[1].rot[0][2], g_eyeRel[1].rot[1][2], g_eyeRel[1].rot[2][2]);
        } else if (a_verb == "stereoshadow") {
            // depth-only pass signatures (shadow cascades) for the next n frames (log: stereoshadow lines)
            if (a_arg == "dump") {
                g_shadowDump.store(1);
                return "dumping the depth-only draws of the next full frame (log: stereoshadowdump lines)";
            }
            const int n = a_arg.empty() ? 1 : std::clamp(std::atoi(a_arg.c_str()), 0, 2000);
            g_shadowFrames.store(n);
            return std::format("logging {} frames (stereoshadow lines)", n);
        } else if (a_verb == "stereotiled") {
            // per-eye tiled lighting: 1 on (default), 0 off (the cut keeps lights on the volume path), mono = A/B test only:
            // tiled lighting kept but dispatched mono over the double-wide image (the pre-twin behaviour, wrong per eye)
            if (a_arg == "mono") {
                g_tiledMonoTest.store(true);
                g_tiledEye.store(true);
            } else if (!a_arg.empty() && a_arg != "status") {
                g_tiledMonoTest.store(false);
                g_tiledEye.store(on);
            }
            return std::format("tiledEye={} monoTest={} available={} aligned={} twins {} (fail {}) conv {} | split dispatches cull {} shade {} "
                               "mono {} fallback {} | {}",
                g_tiledEye.load() ? 1 : 0, g_tiledMonoTest.load() ? 1 : 0, TiledAvailable() ? 1 : 0, TiledAligned() ? 1 : 0,
                g_tiledTwins.load(), g_tiledTwinFails.load(), g_tiledConv.load(), g_tiledSplit[0], g_tiledSplit[1], g_tiledMono,
                g_tiledFail, internal::CutsStatus());
        } else if (a_verb == "stereopasscap") {
            // one frame: halves identity of every pass's output (log: stereopass lines)
            std::scoped_lock l(g_capLock);
            if (g_pc.state != 0) {
                return "busy";
            }
            // stereopasscap <tag> [<dir> <groups: g,g,... | all>]: optional BMPs of the listed PS groups' outputs
            char tag[128]{}, dir[400]{}, groups[256]{};
            const int n = std::sscanf(a_arg.c_str(), "%127s %399s %255s", tag, dir, groups);
            g_pc.tag = n >= 1 ? tag : "pc";
            g_pc.bmpDir = n >= 3 ? dir : "";
            g_pc.bmpGroups.clear();
            if (n >= 3) {
                if (std::string_view(groups) == "all") {
                    g_pc.bmpGroups.push_back(-2);
                } else {
                    for (const char* q = groups; *q;) {
                        g_pc.bmpGroups.push_back(std::atoi(q));
                        while (*q && *q != ',') {
                            ++q;
                        }
                        if (*q == ',') {
                            ++q;
                        }
                    }
                }
            }
            g_pc.state = 1;
            return "requested (log: stereopass lines)";
        } else if (a_verb == "stereostagecap") {
            if (a_arg.empty()) {
                return "error: stereostagecap needs a path stem";
            }
            RequestStageCapture(a_arg);
            return "requested (log: stereostage lines)";
        } else if (a_verb == "stereocuts") {
            // auto = only while frames are rendered in stereo (default), force = also in mono (A/B cost), off = never
            if (a_arg == "auto") {
                c.forceCuts = 0;
            } else if (a_arg == "force") {
                c.forceCuts = 1;
            } else if (a_arg == "off") {
                c.forceCuts = -1;
            } else if (!a_arg.empty() && a_arg != "status") {
                return "error: stereocuts auto|force|off|status";
            }
            if (a_arg.empty() || a_arg == "status") {
                return internal::CutsStatus();
            }
        } else if (a_verb == "stereocut") {
            // stereocut taa|mb|dof|flare|godrays|ssr|hbao|tiled|saops 0|1
            const auto sp = a_arg.find(' ');
            const std::string name = a_arg.substr(0, sp);
            const bool        v = sp != std::string::npos && std::atoi(a_arg.c_str() + sp + 1) != 0;
            bool* const       field = name == "taa"       ? &c.cutTaa :
                                      name == "mb"        ? &c.cutMotionBlur :
                                      name == "dof"       ? &c.cutDof :
                                      name == "flare"     ? &c.cutLensFlare :
                                      name == "godrays"   ? &c.cutGodrays :
                                      name == "ssr"       ? &c.cutSsr :
                                      name == "hbao"      ? &c.cutHbao :
                                      name == "tiled"     ? &c.cutTiled :
                                      name == "saops"     ? &c.saoPixelShader :
                                      name == "sao"       ? &c.cutSao :
                                                            nullptr;
            if (!field || sp == std::string::npos) {
                return "error: stereocut taa|mb|dof|flare|godrays|ssr|hbao|tiled|saops 0|1";
            }
            *field = v;
        } else {
            return "";
        }
        Configure(c);
        return Status() + " | " + internal::CutsStatus();
    }

    std::string Status()
    {
        const Config c = CurrentConfig();
        std::string cap;
        {
            std::scoped_lock l(g_capLock);
            cap = g_capPath.empty() ? "idle" : g_capArmed ? "armed" : "requested";
            cap += g_gbCap.state ? " gbcap=busy" : " gbcap=idle";
            cap += g_stageCap.state ? " stagecap=busy" : " stagecap=idle";
            cap += std::format(" split={} saoPerEye={} b12={} stereoFrames={}", c.split ? 1 : 0, c.saoPerEye ? 1 : 0,
                g_trB12.res ? 1 : 0, g_lastFrameStereo ? 1 : 0);
        }
        return std::format("stereo mode={} hooks={} prepass={} ownDepth={} firstPerson={} scope={} skip={} clear={} testEyes={} ipd={:.3f}m "
                           "fov={:.1f} noJitter={} gate={} frames={} vsCreated={} matched={} convertible={} twins={} cb={} cap={}",
            static_cast<int>(c.mode), g_ctx != nullptr ? 1 : 0, c.stereoPrepass ? 1 : 0, c.ownDepth ? 1 : 0, c.firstPerson ? 1 : 0, c.scope,
            c.skipUnconverted ? 1 : 0, c.clearGBuffer ? 1 : 0, c.testEyes ? 1 : 0, c.testIpdMeters, c.testHalfFovDeg, c.noJitter ? 1 : 0,
            g_gateCam.load(), g_stats.frames, g_vsCreated.load(), g_vsMatched.load(), g_vsConvertible.load(), g_vsTwins.load(),
            static_cast<void*>(g_cb), cap);
    }
