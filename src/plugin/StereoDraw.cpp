        // ---- SAO RawAO (g125): view position = z * ((pixel + 0.5) * cb2[0].xy + cb2[0].zw), pixel in [0, cb2[2].xy).
        // One projInfo for the double-wide image skews each eye; per eye: x over the half's pixels maps to the eye's
        // tangents [l_e, r_e], y to [t_e, b_e]. The engine's mono values are matched against the mono frustum first
        // (sign/orientation), the eye values follow the same convention.
        bool SaoEyeProjInfo(const float* a_cb, int a_eye, float a_out[4], bool a_eyeRelative)
        {
            const double sx = a_cb[0], sy = a_cb[1], ox = a_cb[2], oy = a_cb[3], nx = a_cb[8], ny = a_cb[9];
            if (!g_tanValid || nx < 2 || ny < 1) {
                return false;
            }
            const double l = g_monoTan[0], r = g_monoTan[1], t = g_monoTan[2], b = g_monoTan[3];
            const double le = g_eyeTan[a_eye][0], re = g_eyeTan[a_eye][1], te = g_eyeTan[a_eye][2], be = g_eyeTan[a_eye][3];
            auto close = [](double v, double w) { return std::abs(v - w) <= 0.03 * (std::max)(std::abs(w), 1e-3); };
            // x: ox = s * (l or r), span sx * nx = s * (r - l) or s * (l - r)
            double xs = 0, xe = 0;
            bool   okx = false;
            for (int s = 1; s >= -1 && !okx; s -= 2) {
                if (close(ox, s * l) && close(ox + sx * nx, s * r)) {
                    xs = s * le, xe = s * re, okx = true;
                } else if (close(ox, s * r) && close(ox + sx * nx, s * l)) {
                    xs = s * re, xe = s * le, okx = true;
                }
            }
            double ys = 0, ye = 0;
            bool   oky = false;
            for (int s = 1; s >= -1 && !oky; s -= 2) {
                if (close(oy, s * t) && close(oy + sy * ny, s * b)) {
                    ys = s * te, ye = s * be, oky = true;
                } else if (close(oy, s * b) && close(oy + sy * ny, s * t)) {
                    ys = s * be, ye = s * te, oky = true;
                }
            }
            if (g_saoLogs < 4) {
                ++g_saoLogs;
                REX::INFO("stereo: SAO projInfo mono ({:.5f} {:.5f} {:.5f} {:.5f}) size {}x{} | mono tan l{:.4f} r{:.4f} t{:.4f} b{:.4f} | x {} y {}",
                    sx, sy, ox, oy, nx, ny, l, r, t, b, okx ? "matched" : "NO MATCH", oky ? "matched" : "NO MATCH");
            }
            if (!okx || !oky) {
                g_saoMathOk = false;
                return false;
            }
            const double half = nx * 0.5;
            const double sxe = (xe - xs) / half;
            // (guard bands, RenderSize.h: both eyes have the same layout inside their region, so region-relative pixel
            // positions of the same view direction are equal in both eyes)
            a_out[0] = static_cast<float>(sxe);
            a_out[1] = static_cast<float>((ye - ys) / ny);
            a_out[2] = static_cast<float>(a_eyeRelative ? xs : xs - a_eye * half * sxe);
            a_out[3] = static_cast<float>(ys);
            if (a_eyeRelative) {
                a_out[15] = static_cast<float>(a_eye * half);  // cb2[3].w: the twin subtracts it from pixel x
                // cb2[4]: RawAO's edge bias grows with |screen NDC|^2; the twin feeds it the MONO NDC of the pixel's view
                // direction (eye tangent / mono half-tangent), so asymmetric HMD eyes get mono's bias (eye-local NDC put the
                // eye borders at |NDC| = 1 where mono has ~0.6: SAO too weak towards the eye edges, s4e Meta Quest 3)
                const double r_m = std::abs(r), t_m = std::abs(t);
                if (r_m > 1e-6 && t_m > 1e-6 && g_saoMonoBias.load(std::memory_order_relaxed)) {
                    a_out[16] = static_cast<float>((re - le) / r_m);       // x: u_rel (0..0.5 over the eye region)
                    a_out[17] = static_cast<float>(le / (2.0 * r_m) + 0.5);
                    a_out[18] = static_cast<float>((te - be) / (2.0 * t_m));  // y: v (0..1)
                    a_out[19] = static_cast<float>(0.5 - te / (2.0 * t_m));
                } else {
                    a_out[16] = 2.0f, a_out[17] = 0.0f, a_out[18] = 1.0f, a_out[19] = 0.0f;
                }
            }
            return true;
        }

        // per-eye copies of the SAO cb2 with row 0 replaced; false = draw with the engine's cb2
        bool PrepareSaoCb(ID3D11DeviceContext* a_ctx, bool a_eyeRelative)
        {
            if (g_tanIdentity || !g_saoMathOk) {
                return false;
            }
            ID3D11Buffer* bound = nullptr;
            a_ctx->PSGetConstantBuffers(2, 1, &bound);
            if (!bound) {
                return false;
            }
            bool ok = false;
            if (bound != g_trSao.res) {
                D3D11_BUFFER_DESC bd{};
                bound->GetDesc(&bd);
                if (bd.ByteWidth <= sizeof(g_trSao.data) && bd.ByteWidth >= 48 && !g_trSao.res) {
                    g_trSao.res = bound;  // tracked from the next Map on: per-eye from the next frame
                    g_trSao.size = bd.ByteWidth;
                    REX::INFO("stereo: SAO cb2 = pool buffer {} ({} bytes), tracked", static_cast<void*>(bound), bd.ByteWidth);
                }
            } else if (g_trSao.writes > 0) {
                const UINT saoSize = (std::max)(g_trSao.size, 80u);  // + row 4 for the RawAO twin (radial-bias uv map)
                if (!g_saoCb[0] || g_saoCbSize != saoSize) {
                    for (auto*& b : g_saoCb) {
                        if (b) {
                            b->Release();
                            b = nullptr;
                        }
                    }
                    D3D11_BUFFER_DESC bd{};
                    bd.ByteWidth = saoSize;
                    bd.Usage = D3D11_USAGE_DYNAMIC;
                    bd.BindFlags = D3D11_BIND_CONSTANT_BUFFER;
                    bd.CPUAccessFlags = D3D11_CPU_ACCESS_WRITE;
                    g_saoCbSize = saoSize;
                    for (auto*& b : g_saoCb) {
                        if (FAILED(g_device->CreateBuffer(&bd, nullptr, &b))) {
                            b = nullptr;
                        }
                    }
                }
                ok = g_saoCb[0] && g_saoCb[1];
                for (int e = 0; ok && e < 2; ++e) {
                    alignas(16) std::uint8_t tmp[sizeof(g_trSao.data)]{};
                    std::memcpy(tmp, g_trSao.data, g_trSao.size);
                    ok = SaoEyeProjInfo(reinterpret_cast<const float*>(g_trSao.data), e, reinterpret_cast<float*>(tmp), a_eyeRelative);
                    D3D11_MAPPED_SUBRESOURCE m{};
                    if (ok && SUCCEEDED(a_ctx->Map(g_saoCb[e], 0, D3D11_MAP_WRITE_DISCARD, 0, &m))) {
                        std::memcpy(m.pData, tmp, saoSize);
                        a_ctx->Unmap(g_saoCb[e], 0);
                    } else {
                        ok = false;
                    }
                }
            }
            bound->Release();
            return ok;
        }

        ID3D11RasterizerState* ScissorClone(ID3D11RasterizerState* a_rs, bool& a_engineScissor)
        {
            if (const auto it = g_rsClone.find(a_rs); it != g_rsClone.end()) {
                a_engineScissor = it->second.second;
                return it->second.first;
            }
            D3D11_RASTERIZER_DESC d{};
            if (a_rs) {
                a_rs->GetDesc(&d);
            } else {
                d.FillMode = D3D11_FILL_SOLID;
                d.CullMode = D3D11_CULL_BACK;
                d.DepthClipEnable = TRUE;
            }
            a_engineScissor = d.ScissorEnable != FALSE;
            d.ScissorEnable = TRUE;
            ID3D11RasterizerState* clone = nullptr;
            if (FAILED(g_device->CreateRasterizerState(&d, &clone))) {
                clone = nullptr;
            }
            g_rsClone[a_rs] = { clone, a_engineScissor };
            return clone;
        }

        // Engine scissor rects (e.g. a light's screen bounds) are computed with the MONO projection over the double-wide
        // viewport. Intersecting that rect directly with an eye's half clips the wrong pixels: the mono rect covers view
        // directions, the eye region maps the same directions to other pixels. g_scissorMode: 0 = old (intersect the mono
        // rect as is), 1 = remap the rect's view directions into the eye's region (+ margin for the eye offset), 2 = drop
        // the engine scissor in split draws (eye half only). Pipe "stereoscissor 0|1|2|log".
        std::atomic<int>  g_scissorMode{ 1 };
        std::atomic<int>  g_scissorLog{ 0 };  // split draws with an engine scissor still to log (pipe "stereoscissor log")
        std::uint64_t     g_scissorDraws = 0, g_scissorClipped = 0;

        D3D11_RECT EyeHalfScissor(const D3D11_VIEWPORT& a_vp, int a_e, const D3D11_RECT* a_engine, int a_group)
        {
            const LONG x0 = static_cast<LONG>(a_vp.TopLeftX), y0 = static_cast<LONG>(a_vp.TopLeftY);
            const LONG w = static_cast<LONG>(a_vp.Width), h = static_cast<LONG>(a_vp.Height), hw = w / 2;
            D3D11_RECT half{ x0 + a_e * hw, y0, a_e ? x0 + w : x0 + hw, y0 + h };
            if (!a_engine) {
                return half;
            }
            const int  mode = g_scissorMode.load(std::memory_order_relaxed);
            D3D11_RECT src = *a_engine;
            if (mode == 1 && g_tanValid && !g_tanIdentity) {
                const double l = g_monoTan[0], r = g_monoTan[1], t = g_monoTan[2], b = g_monoTan[3];
                const double le = g_eyeTan[a_e][0], re = g_eyeTan[a_e][1], te = g_eyeTan[a_e][2], be = g_eyeTan[a_e][3];
                const double W = a_vp.Width, H = a_vp.Height;
                auto mx = [&](double px) {
                    const double tx = l + (px - a_vp.TopLeftX) / W * (r - l);
                    return a_vp.TopLeftX + a_e * W * 0.5 + (tx - le) / (re - le) * W * 0.5;
                };
                auto my = [&](double py) {
                    const double ty = t - (py - a_vp.TopLeftY) / H * (t - b);
                    return a_vp.TopLeftY + (te - ty) / (te - be) * H;
                };
                // margin for the eye's offset from the mono origin (parallax of the bounded volume): a quarter of the
                // rect's own extent in the eye + 16 px
                double ax = mx(src.left), bx = mx(src.right), ay = my(src.top), by = my(src.bottom);
                const double mxg = 0.25 * (bx - ax) + 16.0, myg = 0.25 * (by - ay) + 16.0;
                src.left = static_cast<LONG>(std::floor(ax - mxg));
                src.right = static_cast<LONG>(std::ceil(bx + mxg));
                src.top = static_cast<LONG>(std::floor(ay - myg));
                src.bottom = static_cast<LONG>(std::ceil(by + myg));
            }
            D3D11_RECT r = half;
            if (mode != 2) {
                r.left = (std::max)(r.left, src.left);
                r.top = (std::max)(r.top, src.top);
                r.right = (std::min)(r.right, src.right);
                r.bottom = (std::min)(r.bottom, src.bottom);
                if (r.right < r.left) {
                    r.right = r.left;
                }
                if (r.bottom < r.top) {
                    r.bottom = r.top;
                }
            }
            ++g_scissorDraws;
            g_scissorClipped += (r.left != half.left || r.right != half.right || r.top != half.top || r.bottom != half.bottom);
            if (g_scissorLog.load(std::memory_order_relaxed) > 0) {
                g_scissorLog.fetch_sub(1);
                REX::INFO("stereoscissor: g{:03} eye {} viewport {:.0f},{:.0f} {:.0f}x{:.0f} | engine rect {},{} - {},{} | mode {} -> {},{} - {},{} "
                          "(half {} - {})",
                    a_group, a_e, a_vp.TopLeftX, a_vp.TopLeftY, a_vp.Width, a_vp.Height, a_engine->left, a_engine->top, a_engine->right,
                    a_engine->bottom, mode, r.left, r.top, r.right, r.bottom, half.left, half.right);
            }
            return r;
        }

        // M2: the draw twice, each time with b12 = the eye's copy (VS + PS) and the scissor on that half of the viewport.
        template <class F>
        void RunSplit(ID3D11DeviceContext* a_ctx, F&& a_draw)
        {
            ID3D11Buffer* vs12 = nullptr;
            ID3D11Buffer* ps12 = nullptr;
            a_ctx->VSGetConstantBuffers(12, 1, &vs12);
            a_ctx->PSGetConstantBuffers(12, 1, &ps12);
            ID3D11RasterizerState* rs = nullptr;
            a_ctx->RSGetState(&rs);
            UINT           nvp = 1;
            D3D11_VIEWPORT vp{};
            a_ctx->RSGetViewports(&nvp, &vp);
            D3D11_RECT sc[D3D11_VIEWPORT_AND_SCISSORRECT_OBJECT_COUNT_PER_PIPELINE]{};
            UINT       nsc = D3D11_VIEWPORT_AND_SCISSORRECT_OBJECT_COUNT_PER_PIPELINE;
            a_ctx->RSGetScissorRects(&nsc, sc);
            bool                         engineScissor = false;
            ID3D11RasterizerState* const clone = ScissorClone(rs, engineScissor);
            ID3D11Buffer*                ps2 = nullptr;
            ID3D11PixelShader* const     saoTwin =
                g_splitSao && g_saoEyeNoise.load(std::memory_order_relaxed) && g_s.psInfo ? g_s.psInfo->twin : nullptr;
            const bool                   sao = g_splitSao && PrepareSaoCb(a_ctx, saoTwin != nullptr);
            const bool                   useTwin = sao && saoTwin;
            if (useTwin) {
                o_psSet(a_ctx, saoTwin, nullptr, 0);
                ++g_stats.splitSaoTwin;
            }
            if (sao) {
                a_ctx->PSGetConstantBuffers(2, 1, &ps2);
                ++g_stats.splitSaoFixed;
            }
            if (!clone || nvp == 0 || vp.Width < 2.0f) {
                ++g_stats.splitFallback;
                a_draw();
            } else {
                a_ctx->RSSetState(clone);
                for (int e = 0; e < 2; ++e) {
                    a_ctx->VSSetConstantBuffers(12, 1, &g_b12Eye[e]);
                    a_ctx->PSSetConstantBuffers(12, 1, &g_b12Eye[e]);
                    if (sao) {
                        a_ctx->PSSetConstantBuffers(2, 1, &g_saoCb[e]);
                    }
                    const D3D11_RECT r = EyeHalfScissor(vp, e, engineScissor && nsc > 0 ? &sc[0] : nullptr,
                        g_s.psInfo ? g_s.psInfo->group : -1);
                    a_ctx->RSSetScissorRects(1, &r);
                    a_draw();
                }
                a_ctx->VSSetConstantBuffers(12, 1, &vs12);
                a_ctx->PSSetConstantBuffers(12, 1, &ps12);
                a_ctx->RSSetState(rs);
                a_ctx->RSSetScissorRects(nsc, nsc ? sc : nullptr);
                if (sao) {
                    a_ctx->PSSetConstantBuffers(2, 1, &ps2);
                }
            }
            if (useTwin) {
                o_psSet(a_ctx, g_s.boundOurPS ? g_s.boundOurPS : g_s.enginePS, nullptr, 0);
            }
            for (IUnknown* u : { static_cast<IUnknown*>(vs12), static_cast<IUnknown*>(ps12), static_cast<IUnknown*>(rs),
                     static_cast<IUnknown*>(ps2) }) {
                if (u) {
                    u->Release();
                }
            }
        }

