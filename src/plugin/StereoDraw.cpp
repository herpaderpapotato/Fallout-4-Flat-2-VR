// StereoDraw.cpp - D3D11-level draw conversion.
//
// Why the D3D level (and not Renderer::DrawTriShape & co.): every engine path ends in the immediate
// context - Renderer::DrawTriShape 1818E80 (DrawIndexed), DrawInstancedTriShape 1819290
// (DrawIndexedInstanced), ProcessCommandBuffer 1820BF0 (direct DrawIndexed/Draw on replayed records) and
// DoZPrePass 181FAA0 (direct VSSetShader/Draw). Verified: no deferred contexts exist in 1.11.240 (all
// Renderer::SetContext callers pass a null Context; the only Context has deferredContext = 0), so one
// vtable patch of the immediate context sees every draw of every pass, recorded or not. The vtable is per
// class inside d3d11.dll, so other in-process contexts (OpenXR runtime, overlays) also pass through these
// hooks: everything is gated on `this == g_ctx`.
//
// Shader identity: CreateVertexShader is hooked on the device right after D3D11CreateDeviceAndSwapChain
// (before the engine loads Shaders011.fxp); each blob's 16-byte DXBC checksum is looked up in
//   - StereoVS.pack (stereo_shaders/, generated by proto/stereo/tools/gen_stereo_vs.py): the bytecode twin of
//     every camera-dependent engine VS (original program + per-eye clip correction + squeeze + seam clip);
//   - StereoTargets.inl: the PoC's two g008 static families (HLSL debug shaders with the world-cell hash PS).
// VS objects live for the whole session (created once at load), so the pointer maps are insert-only.
//
// Conversion (per draw, only on g_ctx, only while a stereo camera is applied = world or 1st-person camera):
//   draw in scope (GBuffer writer or z-prepass; iScope=1: any) and the bound VS has a twin
//        -> bind the twin (+ debug/marker PS), b5, and for per-instance input layouts a twin layout with
//           InstanceDataStepRate x2; issue the draw with 2x the instances (eye = id & 1, original = id >> 1)
//   otherwise -> restore the engine's VS/PS/layout if ours is still bound, draw as is
// The engine's own state shadowing never sees our swaps (we restore exactly what it last set).

