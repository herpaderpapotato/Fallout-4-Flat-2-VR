        // Constant buffers whose engine-written content we need on the CPU: the Map hook hands the engine a shadow
        // copy and the Unmap hook copies it into the real (write-combined) mapping.
        struct Tracked
        {
            ID3D11Resource* res{ nullptr };
            UINT            size{ 0 };
            void*           real{ nullptr };
            bool            mapped{ false };
            std::uint64_t   writes{ 0 };
            alignas(16) std::uint8_t data[0x800]{};
        };
        Tracked g_trB12;  // the engine's per-frame buffer (BSGraphics::Context+0x1B38, 0x2F0 bytes, b12)
        Tracked g_trSao;  // the pool buffer the SAO RawAO pass binds as cb2 (shared by every 64-byte constant group)
        // further cb2 pool buffers read by the per-eye post passes (StereoPost.inl): registered at first use, content
        // tracked from the next Map on (render thread only)
        constexpr int kTrPool = 16;
        Tracked       g_trPool[kTrPool];
        int           g_trPoolN = 0;
        bool    g_inCamApply = false;
        bool    g_b12WrittenInApply = false;
        std::uint64_t g_b12NotWritten = 0;

        struct EyeB12Input
        {
            bool         valid{ false };
            int          cam{ 0 };
            math::M4     V, P, VP;
            math::EyeRel eyes[2];
            float        fr[6]{};
            bool         identity{ false };
            double       jx{ 0 }, jy{ 0 };  // TAA jitter of the application (clip-space translation)
            double       pa[3]{};           // posAdjust (camera-relative origin)
        };
        EyeB12Input   g_b12In;

        // ---- per-eye motion vectors for TAA (stereo-lighting.md, item 0b) ----------------------------------------
        // The GBuffer PS write the motion vector with the mono rows 31-40: mv = uv_prev - uv_cur of the surface point in
        // MONO double-wide UV. Just before TAA reads it, a fullscreen pass converts it per eye: the pixel's surface point
        // (eye unprojection of its depth) -> its mono UV -> + mv = its previous mono UV -> back along that ray at the
        // previous view depth (static-world prediction for world pixels, unchanged for 1st-person pixels) -> the eye's
        // previous UV. History taps are clamped to the eye's half (no cross-seam history).
        struct MvFixConstants
        {
            float invEye[2][16];   // DW NDC (x, y, z_ndc, 1) of eye e -> mono view (homogeneous), world camera
            float eyeP[2][16];     // mono view -> DW clip of eye e (unjittered)
            float monoP[16];       // mono view -> mono DW clip (unjittered)
            float invMonoP[16];
            float invEye1[2][16];  // the same for the 1st-person camera (depth <= 0.01)
            float eyeP1[2][16];
            float monoP1[16];
            float invMonoP1[16];
            float prevFromCur[16]; // mono view (t) -> mono view (t-1), static world
            float size[4];         // DW width, height, eye width, unused
            float misc[4];         // x clamp margin px, y sign (+1: mv = uv_prev - uv_cur), z have 1st-person, w unused
        };
        static_assert(sizeof(MvFixConstants) % 16 == 0);
        MvFixConstants g_mvk{};
        bool           g_mvkValid = false;
        std::uint64_t  g_mvkFrame = ~0ull;           // frame index of g_curV
        math::M4       g_curV, g_prevV;
        double         g_curPa[3]{}, g_prevPa[3]{};
        bool           g_prevVValid = false, g_curVValid = false;
        int            g_mvSign = 0;                 // +1 rows 37-40 = current VP (mv = uv_prev - uv_cur), -1 reversed, 0 unknown
        int            g_mvSignLogs = 0;
        std::atomic<bool> g_taaPerEye{ true };
        bool           g_mvFixDone = false;          // this frame
        double         g_jitOff = 0, g_jitX = 0, g_jitY = 0;
        ID3D11Buffer* g_b12Eye[2]{};
        bool          g_b12EyeValid = false;
        int           g_b12Conv[4]{ -1, -1, -1, -1 };  // rows 4/8/16/20: 0 stored transposed, 1 as is
        int           g_b12ConvLogs = 0;
        double        g_firstN = 0, g_firstF = 0;      // 1st-person near/far recovered from rows 24-27 (log)
        // SAO per-eye projInfo: mono / eye frustum tangents (l, r, t, b) of the last world-camera build
        float         g_monoTan[4]{}, g_eyeTan[2][4]{};
        math::EyeRel  g_eyeRel[2];  // eyes (rotation, padded tangents) of the last world-camera build
        bool          g_tanValid = false, g_tanIdentity = false;
        ID3D11Buffer* g_saoCb[2]{};
        UINT          g_saoCbSize = 0;
        int           g_saoLogs = 0;
        bool          g_saoMathOk = true;

        // split-draw state of the draw being issued
