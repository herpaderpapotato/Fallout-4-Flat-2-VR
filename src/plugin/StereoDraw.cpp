        // ---- capture write-out ---------------------------------------------------------------------
        float HalfToFloat(std::uint16_t h)
        {
            const std::uint32_t s = (h >> 15) & 1, e = (h >> 10) & 31, m = h & 1023;
            float v = e == 0 ? std::ldexp(static_cast<float>(m), -24) : e == 31 ? 65504.0f : std::ldexp(static_cast<float>(m | 1024), static_cast<int>(e) - 25);
            return s ? -v : v;
        }

        // DXGI format -> bytes per texel and how to compare channels (0 unknown/bitwise only, 1 unorm8 x4, 2 r10g10b10a2,
        // 3 float16 x n, 4 float32 x n, 5 r11g11b10 float, 6 unorm16 x n)
        struct FmtInfo
        {
            UINT bpp{ 0 };
            int  kind{ 0 };
            int  channels{ 0 };
        };
        FmtInfo Fmt(DXGI_FORMAT a_f)
        {
            switch (a_f) {
            case DXGI_FORMAT_R8G8B8A8_UNORM:
            case DXGI_FORMAT_R8G8B8A8_UNORM_SRGB:
            case DXGI_FORMAT_R8G8B8A8_TYPELESS:
            case DXGI_FORMAT_B8G8R8A8_UNORM:
            case DXGI_FORMAT_B8G8R8A8_UNORM_SRGB:
            case DXGI_FORMAT_B8G8R8A8_TYPELESS:
            case DXGI_FORMAT_R8G8B8A8_SNORM:
                return { 4, 1, 4 };
            case DXGI_FORMAT_R10G10B10A2_UNORM:
            case DXGI_FORMAT_R10G10B10A2_TYPELESS:
                return { 4, 2, 4 };
            case DXGI_FORMAT_R16G16B16A16_FLOAT:
            case DXGI_FORMAT_R16G16B16A16_TYPELESS:
                return { 8, 3, 4 };
            case DXGI_FORMAT_R16G16_FLOAT:
            case DXGI_FORMAT_R16G16_TYPELESS:
                return { 4, 3, 2 };
            case DXGI_FORMAT_R16_FLOAT:
                return { 2, 3, 1 };
            case DXGI_FORMAT_R32_FLOAT:
                return { 4, 4, 1 };
            case DXGI_FORMAT_R32G32_FLOAT:
                return { 8, 4, 2 };
            case DXGI_FORMAT_R32G32B32A32_FLOAT:
                return { 16, 4, 4 };
            case DXGI_FORMAT_R11G11B10_FLOAT:
                return { 4, 5, 3 };
            case DXGI_FORMAT_R8G8_UNORM:
                return { 2, 1, 2 };
            case DXGI_FORMAT_R16G16_UNORM:
            case DXGI_FORMAT_R16G16_SNORM:
                return { 4, 6, 2 };
            case DXGI_FORMAT_R16G16B16A16_UNORM:
                return { 8, 6, 4 };
            case DXGI_FORMAT_R8_UNORM:
                return { 1, 1, 1 };
            default:
                return {};
            }
        }

        // true if two texels are within one step of the format's precision in every channel
        bool Near(const std::uint8_t* a, const std::uint8_t* b, const FmtInfo& f)
        {
            switch (f.kind) {
            case 1:
                for (int c = 0; c < f.channels; ++c) {
                    if (std::abs(int(a[c]) - int(b[c])) > 1) {
                        return false;
                    }
                }
                return true;
            case 2: {
                std::uint32_t p, q;
                std::memcpy(&p, a, 4);
                std::memcpy(&q, b, 4);
                for (int c = 0; c < 3; ++c) {
                    if (std::abs(int((p >> (10 * c)) & 1023) - int((q >> (10 * c)) & 1023)) > 1) {
                        return false;
                    }
                }
                return ((p >> 30) == (q >> 30));
            }
            case 3:
                for (int c = 0; c < f.channels; ++c) {
                    std::uint16_t h1, h2;
                    std::memcpy(&h1, a + 2 * c, 2);
                    std::memcpy(&h2, b + 2 * c, 2);
                    const float x = HalfToFloat(h1), y = HalfToFloat(h2);
                    if (std::fabs(x - y) > 1e-3f * (std::max)(1.0f, (std::max)(std::fabs(x), std::fabs(y)))) {
                        return false;
                    }
                }
                return true;
            case 4:
                for (int c = 0; c < f.channels; ++c) {
                    float x, y;
                    std::memcpy(&x, a + 4 * c, 4);
                    std::memcpy(&y, b + 4 * c, 4);
                    if (std::fabs(x - y) > 1e-4f * (std::max)(1.0f, (std::max)(std::fabs(x), std::fabs(y)))) {
                        return false;
                    }
                }
                return true;
            case 6:
                for (int c = 0; c < f.channels; ++c) {
                    std::uint16_t u, v;
                    std::memcpy(&u, a + 2 * c, 2);
                    std::memcpy(&v, b + 2 * c, 2);
                    if (std::abs(int(u) - int(v)) > 1) {
                        return false;
                    }
                }
                return true;
            default:
                return false;
            }
        }

        // max channel difference in normalised units (8-bit equivalence check for 16-bit / float targets)
        double NormDiff(const std::uint8_t* a, const std::uint8_t* b, const FmtInfo& f)
        {
            double m = 0;
            for (int c = 0; c < f.channels; ++c) {
                double x = 0, y = 0;
                if (f.kind == 1) {
                    x = a[c] / 255.0, y = b[c] / 255.0;
                } else if (f.kind == 6) {
                    std::uint16_t u, v;
                    std::memcpy(&u, a + 2 * c, 2);
                    std::memcpy(&v, b + 2 * c, 2);
                    x = u / 65535.0, y = v / 65535.0;
                } else if (f.kind == 3) {
                    std::uint16_t u, v;
                    std::memcpy(&u, a + 2 * c, 2);
                    std::memcpy(&v, b + 2 * c, 2);
                    x = HalfToFloat(u), y = HalfToFloat(v);
                } else {
                    return std::memcmp(a, b, f.bpp) ? 1.0 : 0.0;
                }
                m = (std::max)(m, std::fabs(x - y));
            }
            return m;
        }

        bool WriteBmp(const std::string& a_path, ID3D11Texture2D* a_staging, const D3D11_MAPPED_SUBRESOURCE& m)
        {
            D3D11_TEXTURE2D_DESC d{};
            a_staging->GetDesc(&d);
            std::vector<std::uint8_t> rgb(static_cast<std::size_t>(d.Width) * d.Height * 4);
            bool ok = true;
            for (UINT y = 0; y < d.Height && ok; ++y) {
                const auto* row = static_cast<const std::uint8_t*>(m.pData) + static_cast<std::size_t>(y) * m.RowPitch;
                for (UINT x = 0; x < d.Width; ++x) {
                    std::uint8_t* o = &rgb[(static_cast<std::size_t>(y) * d.Width + x) * 4];  // B,G,R,X
                    switch (d.Format) {
                    case DXGI_FORMAT_R8G8B8A8_UNORM:
                    case DXGI_FORMAT_R8G8B8A8_UNORM_SRGB:
                    case DXGI_FORMAT_R8G8B8A8_TYPELESS:
                        o[0] = row[x * 4 + 2], o[1] = row[x * 4 + 1], o[2] = row[x * 4 + 0];
                        break;
                    case DXGI_FORMAT_B8G8R8A8_UNORM:
                    case DXGI_FORMAT_B8G8R8A8_UNORM_SRGB:
                    case DXGI_FORMAT_B8G8R8A8_TYPELESS:
                        o[0] = row[x * 4 + 0], o[1] = row[x * 4 + 1], o[2] = row[x * 4 + 2];
                        break;
                    case DXGI_FORMAT_R16G16B16A16_FLOAT:
                    case DXGI_FORMAT_R16G16B16A16_TYPELESS: {
                        std::uint16_t h[4];
                        std::memcpy(h, row + x * 8, 8);
                        for (int c = 0; c < 3; ++c) {
                            const float v = (std::min)(1.0f, (std::max)(0.0f, HalfToFloat(h[c])));
                            o[2 - c] = static_cast<std::uint8_t>(v * 255.0f + 0.5f);
                        }
                    } break;
                    case DXGI_FORMAT_R10G10B10A2_UNORM:
                    case DXGI_FORMAT_R10G10B10A2_TYPELESS: {
                        std::uint32_t p;
                        std::memcpy(&p, row + x * 4, 4);
                        o[2] = static_cast<std::uint8_t>((p & 1023) >> 2);
                        o[1] = static_cast<std::uint8_t>(((p >> 10) & 1023) >> 2);
                        o[0] = static_cast<std::uint8_t>(((p >> 20) & 1023) >> 2);
                    } break;
                    case DXGI_FORMAT_R11G11B10_FLOAT: {
                        std::uint32_t p;
                        std::memcpy(&p, row + x * 4, 4);
                        auto f11 = [](std::uint32_t m, std::uint32_t e, int mb) {
                            const float v = e == 0 ? std::ldexp(static_cast<float>(m), -14 - mb)
                                                   : std::ldexp(static_cast<float>(m | (1u << mb)), static_cast<int>(e) - 15 - mb);
                            return static_cast<std::uint8_t>((std::min)(1.0f, v) * 255.0f + 0.5f);
                        };
                        o[2] = f11(p & 63, (p >> 6) & 31, 6);
                        o[1] = f11((p >> 11) & 63, (p >> 17) & 31, 6);
                        o[0] = f11((p >> 22) & 31, (p >> 27) & 31, 5);
                    } break;
                    case DXGI_FORMAT_R16G16_FLOAT:
                    case DXGI_FORMAT_R16_FLOAT: {
                        const UINT bpp = d.Format == DXGI_FORMAT_R16_FLOAT ? 2 : 4;
                        std::uint16_t h[2]{};
                        std::memcpy(h, row + x * bpp, bpp);
                        const float v = (std::min)(1.0f, (std::max)(0.0f, HalfToFloat(h[0])));
                        o[0] = o[1] = o[2] = static_cast<std::uint8_t>(v * 255.0f + 0.5f);
                    } break;
                    case DXGI_FORMAT_R8_UNORM:
                        o[0] = o[1] = o[2] = row[x];
                        break;
                    default:
                        ok = false;
                    }
                    o[3] = 255;
                }
            }
            if (!ok) {
                REX::ERROR("stereocap: unsupported format {}", static_cast<int>(d.Format));
                return false;
            }
            BITMAPFILEHEADER fh{};
            BITMAPINFOHEADER ih{};
            fh.bfType = 0x4D42;
            fh.bfOffBits = sizeof(fh) + sizeof(ih);
            fh.bfSize = fh.bfOffBits + static_cast<DWORD>(rgb.size());
            ih.biSize = sizeof(ih);
            ih.biWidth = static_cast<LONG>(d.Width);
            ih.biHeight = -static_cast<LONG>(d.Height);
            ih.biPlanes = 1;
            ih.biBitCount = 32;
            ih.biCompression = BI_RGB;
            HANDLE f = ::CreateFileA(a_path.c_str(), GENERIC_WRITE, 0, nullptr, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, nullptr);
            if (f == INVALID_HANDLE_VALUE) {
                return false;
            }
            DWORD w = 0;
            ::WriteFile(f, &fh, sizeof(fh), &w, nullptr);
            ::WriteFile(f, &ih, sizeof(ih), &w, nullptr);
            ::WriteFile(f, rgb.data(), static_cast<DWORD>(rgb.size()), &w, nullptr);
            ::CloseHandle(f);
            return true;
        }

        void WriteSidecar(const std::string& a_path, const D3D11_TEXTURE2D_DESC& d)
        {
            // Sidecar for tools/stereo_metrics.py: everything needed to predict disparity.
            const Config c = CurrentConfig();
            const std::string meta = std::format(
                "{{\"width\": {}, \"height\": {}, \"format\": {}, \"srgb\": {}, \"mode\": {}, \"testEyes\": {}, "
                "\"ipdUnits\": {}, \"tanHalfH\": {}, \"skipUnconverted\": {}, \"noJitter\": {}}}\n",
                d.Width, d.Height, static_cast<int>(d.Format),
                (d.Format == DXGI_FORMAT_R8G8B8A8_UNORM_SRGB || d.Format == DXGI_FORMAT_B8G8R8A8_UNORM_SRGB) ? "true" : "false",
                static_cast<int>(c.mode), c.testEyes ? "true" : "false", c.testIpdMeters * c.unitsPerMeter,
                std::tan(c.testHalfFovDeg * 3.14159265358979 / 180.0), c.skipUnconverted ? "true" : "false",
                c.noJitter ? "true" : "false");
            DWORD w = 0;
            HANDLE j = ::CreateFileA((a_path + ".json").c_str(), GENERIC_WRITE, 0, nullptr, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, nullptr);
            if (j != INVALID_HANDLE_VALUE) {
                ::WriteFile(j, meta.data(), static_cast<DWORD>(meta.size()), &w, nullptr);
                ::CloseHandle(j);
            }
        }

