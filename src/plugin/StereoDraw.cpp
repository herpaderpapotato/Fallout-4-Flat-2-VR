        const TargetRow* FindTarget(const dxbc::Key& a_key)
        {
            for (const auto& r : kTargets) {  // 488 rows, only at shader creation time
                if (std::memcmp(r.key, a_key.b, 16) == 0) {
                    return &r;
                }
            }
            return nullptr;
        }

