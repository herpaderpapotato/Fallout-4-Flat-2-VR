        // texel -> up to 4 float channels (unorm/float formats used by the light/HDR/AO targets); false = unsupported
        bool Decode(const std::uint8_t* a_t, const FmtInfo& a_f, DXGI_FORMAT a_fmt, float a_out[4])
        {
            switch (a_f.kind) {
            case 1:
                for (int c = 0; c < a_f.channels; ++c) {
                    a_out[c] = a_t[c] / 255.0f;
                }
                return true;
            case 2: {
                std::uint32_t p;
                std::memcpy(&p, a_t, 4);
                for (int c = 0; c < 3; ++c) {
                    a_out[c] = ((p >> (10 * c)) & 1023) / 1023.0f;
                }
                a_out[3] = (p >> 30) / 3.0f;
                return true;
            }
            case 3:
                for (int c = 0; c < a_f.channels; ++c) {
                    std::uint16_t h;
                    std::memcpy(&h, a_t + 2 * c, 2);
                    a_out[c] = HalfToFloat(h);
                }
                return true;
            case 4:
                std::memcpy(a_out, a_t, 4 * static_cast<std::size_t>(a_f.channels));
                return true;
            case 5: {
                std::uint32_t p;
                std::memcpy(&p, a_t, 4);
                auto f11 = [](std::uint32_t m, std::uint32_t e, int mb) {
                    return e == 0 ? std::ldexp(static_cast<float>(m), -14 - mb)
                                  : std::ldexp(static_cast<float>(m | (1u << mb)), static_cast<int>(e) - 15 - mb);
                };
                a_out[0] = f11(p & 63, (p >> 6) & 31, 6);
                a_out[1] = f11((p >> 11) & 63, (p >> 17) & 31, 6);
                a_out[2] = f11((p >> 22) & 31, (p >> 27) & 31, 5);
                return true;
            }
            case 6:
                for (int c = 0; c < a_f.channels; ++c) {
                    std::uint16_t u;
                    std::memcpy(&u, a_t + 2 * c, 2);
                    a_out[c] = u / 65535.0f;
                }
                return true;
            default:
                (void)a_fmt;
                return false;
            }
        }

        // Halves identity of one captured stage: exact / within 1% (or 1/255) / within 4% (or 4/255), on the full half
        // and with a 64-px band at the seam and the outer edges excluded (blur kernels may cross the seam).
        void AnalyzeStage(const std::string& a_stem, int a_stage)
        {
            ID3D11Texture2D* st = g_stageCap.staging[a_stage];
            D3D11_TEXTURE2D_DESC d{};
            st->GetDesc(&d);
            FmtInfo f = Fmt(d.Format);
            if (d.Format == DXGI_FORMAT_R11G11B10_FLOAT) {
                f = { 4, 5, 3 };
            }
            D3D11_MAPPED_SUBRESOURCE m{};
            if (!f.bpp || FAILED(g_ctx->Map(st, 0, D3D11_MAP_READ, 0, &m))) {
                REX::WARN("stereostage: {} {} format {} not analysable", a_stem, kStageNames[a_stage], static_cast<int>(d.Format));
                return;
            }
            const UINT half = d.Width / 2;
            const UINT band = (std::min)(64u * d.Width / 2880u + 1u, half / 4);
            std::uint64_t n = 0, same = 0, n1 = 0, n4 = 0, bn = 0, bsame = 0, b1 = 0, b4 = 0, lit = 0;
            double        sumL = 0, sumR = 0;
            for (UINT y = 0; y < d.Height; ++y) {
                const auto* row = static_cast<const std::uint8_t*>(m.pData) + static_cast<std::size_t>(y) * m.RowPitch;
                for (UINT x = 0; x < half; ++x) {
                    const std::uint8_t* a = row + static_cast<std::size_t>(x) * f.bpp;
                    const std::uint8_t* b = row + static_cast<std::size_t>(x + half) * f.bpp;
                    float fa[4]{}, fb[4]{};
                    Decode(a, f, d.Format, fa);
                    Decode(b, f, d.Format, fb);
                    const bool eq = std::memcmp(a, b, f.bpp) == 0;
                    bool w1 = true, w4 = true, nz = false;
                    for (int c = 0; c < (std::min)(f.channels, 3); ++c) {
                        const float da = std::fabs(fa[c] - fb[c]), mx = (std::max)(std::fabs(fa[c]), std::fabs(fb[c]));
                        w1 = w1 && (da <= (std::max)(1.0f / 255.0f, 0.01f * mx) || !(da == da));
                        w4 = w4 && (da <= (std::max)(4.0f / 255.0f, 0.04f * mx) || !(da == da));
                        nz = nz || fa[c] != 0.0f || fb[c] != 0.0f;
                        sumL += fa[c];
                        sumR += fb[c];
                    }
                    ++n;
                    same += eq;
                    n1 += w1;
                    n4 += w4;
                    lit += nz;
                    const bool inBand = x < band || x >= half - band;
                    if (!inBand) {
                        ++bn;
                        bsame += eq;
                        b1 += w1;
                        b4 += w4;
                    }
                }
            }
            const std::string bmp = std::format("{}_{}.bmp", a_stem, kStageNames[a_stage]);
            const bool        bmpOk = WriteBmp(bmp, st, m);
            g_ctx->Unmap(st, 0);
            if (bmpOk) {
                WriteSidecar(bmp, d);
            }
            const double N = n ? static_cast<double>(n) : 1.0, B = bn ? static_cast<double>(bn) : 1.0;
            REX::INFO("stereostage: {} {} {}x{} fmt {} draws {} | identical {:.4f}% within 1% {:.4f}% within 4% {:.4f}% | without {}-px seam/edge band: "
                      "identical {:.4f}% within 1% {:.4f}% within 4% {:.4f}% | nonzero {:.2f}% | mean L {:.5f} R {:.5f}",
                a_stem, kStageNames[a_stage], d.Width, d.Height, static_cast<int>(d.Format), g_stageCap.draws[a_stage], 100.0 * same / N,
                100.0 * n1 / N, 100.0 * n4 / N, band, 100.0 * bsame / B, 100.0 * b1 / B, 100.0 * b4 / B, 100.0 * lit / N, sumL / N, sumR / N);
        }

