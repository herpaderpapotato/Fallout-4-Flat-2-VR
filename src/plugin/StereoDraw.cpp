        const VsInfo* LookupLocked(ID3D11VertexShader* a_vs)
        {
            const auto it = g_vs.find(a_vs);
            return it == g_vs.end() ? nullptr : &it->second;
        }

        void RefreshPrepassVS()
        {
            auto* const base = reinterpret_cast<std::uint8_t*>(::GetModuleHandleW(nullptr));
            bool ready = true;
            int  n = 0;
            std::shared_lock l(g_regLock);
            for (int i = 0; i < 4; ++i) {
                auto* const eng = *reinterpret_cast<std::uint8_t**>(base + kPrepassVS[i]);
                g_prepassVS[i] = eng ? *reinterpret_cast<ID3D11VertexShader**>(eng + 8) : nullptr;
                if (g_prepassVS[i]) {
                    ++n;
                    const VsInfo* vi = LookupLocked(g_prepassVS[i]);
                    ready = ready && vi && vi->twin;
                }
            }
            g_prepassTwinsReady = ready && n > 0;
        }

        bool IsPrepassVS(ID3D11VertexShader* a_vs)
        {
            return a_vs && (a_vs == g_prepassVS[0] || a_vs == g_prepassVS[1] || a_vs == g_prepassVS[2] || a_vs == g_prepassVS[3]);
        }

        ID3D11DepthStencilState* WriteClone(ID3D11DepthStencilState* a_dss)
        {
            if (const auto it = g_dssClone.find(a_dss); it != g_dssClone.end()) {
                return it->second;
            }
            ID3D11DepthStencilState* clone = nullptr;
            D3D11_DEPTH_STENCIL_DESC d{};
            a_dss->GetDesc(&d);
            if (d.DepthEnable && d.DepthWriteMask == D3D11_DEPTH_WRITE_MASK_ZERO) {
                d.DepthWriteMask = D3D11_DEPTH_WRITE_MASK_ALL;
                if (FAILED(g_device->CreateDepthStencilState(&d, &clone))) {
                    clone = nullptr;
                }
            }
            g_dssClone[a_dss] = clone;  // nullptr = no clone needed / possible
            return clone;
        }

