        float HalfF(std::uint16_t h)
        {
            const std::uint32_t sgn = (h >> 15) & 1, e = (h >> 10) & 31, m = h & 1023;
            float v = e == 0 ? std::ldexp(static_cast<float>(m), -24) : e == 31 ? 65504.0f : std::ldexp(static_cast<float>(m | 1024), static_cast<int>(e) - 25);
            return sgn ? -v : v;
        }

        void AnalyzeMvCheck()
        {
            D3D11_MAPPED_SUBRESOURCE m[3]{};
            D3D11_TEXTURE2D_DESC     d{};
            g_mvCheck.st[0]->GetDesc(&d);
            bool ok = true;
            for (int i = 0; i < 3 && ok; ++i) {
                ok = SUCCEEDED(g_ctx->Map(g_mvCheck.st[i], 0, D3D11_MAP_READ, 0, &m[i]));
            }
            if (ok) {
                const MvFixConstants& k = g_mvCheck.k;
                auto M = [](const float* f) { return math::M4::FromFloats(f); };
                const math::M4 invEye[2] = { M(k.invEye[0]), M(k.invEye[1]) }, eyeP[2] = { M(k.eyeP[0]), M(k.eyeP[1]) };
                const math::M4 pfc = M(k.prevFromCur);
                auto xf = [](const double v[4], const math::M4& a, double o[4]) {
                    for (int j = 0; j < 4; ++j) {
                        o[j] = v[0] * a.m[0][j] + v[1] * a.m[1][j] + v[2] * a.m[2][j] + v[3] * a.m[3][j];
                    }
                };
                const double W2 = d.Width, H = d.Height;
                std::vector<double> errFix, errRaw, mag;
                double              sumFixX = 0, sumFixY = 0;
                for (UINT y = 8; y < d.Height; y += 16) {
                    for (UINT x = 8; x < d.Width; x += 16) {
                        const auto* raw = reinterpret_cast<const std::uint16_t*>(static_cast<const std::uint8_t*>(m[0].pData) + y * m[0].RowPitch) + 2 * x;
                        const auto* fix = reinterpret_cast<const std::uint16_t*>(static_cast<const std::uint8_t*>(m[1].pData) + y * m[1].RowPitch) + 2 * x;
                        const auto* dp = static_cast<const std::uint8_t*>(m[2].pData) + y * m[2].RowPitch;
                        double dep = 0;
                        if (g_mvCheck.depthFmt == DXGI_FORMAT_R24_UNORM_X8_TYPELESS) {
                            std::uint32_t v;
                            std::memcpy(&v, dp + 4 * x, 4);
                            dep = (v & 0xFFFFFF) / 16777215.0;
                        } else if (g_mvCheck.depthFmt == DXGI_FORMAT_R32_FLOAT || g_mvCheck.depthFmt == DXGI_FORMAT_R32_FLOAT_X8X24_TYPELESS) {
                            float v;
                            std::memcpy(&v, dp + (g_mvCheck.depthFmt == DXGI_FORMAT_R32_FLOAT ? 4 : 8) * x, 4);
                            dep = v;
                        } else {
                            continue;
                        }
                        if (dep <= 0.01 || dep >= 0.99999) {
                            continue;  // world pixels only (1st-person and empty/sky excluded)
                        }
                        const int    e = x >= d.Width / 2 ? 1 : 0;
                        const double u = (x + 0.5) / W2, v = (y + 0.5) / H;
                        const double c[4] = { u * 2 - 1, 1 - v * 2, dep * 1.01 - 0.01, 1 };
                        double       vw[4], vp[4], cp[4], cc[4];
                        xf(c, invEye[e], vw);
                        for (double& t : vw) {
                            t /= vw[3];
                        }
                        xf(vw, pfc, vp);
                        xf(vp, eyeP[e], cp);
                        xf(vw, eyeP[e], cc);
                        if (cp[3] <= 0 || cc[3] <= 0) {
                            continue;
                        }
                        const double ex = (cp[0] / cp[3] - cc[0] / cc[3]) * 0.5 * W2, ey = -(cp[1] / cp[3] - cc[1] / cc[3]) * 0.5 * H;
                        const double fx = HalfF(fix[0]) * W2, fy = HalfF(fix[1]) * H;
                        const double rx = HalfF(raw[0]) * W2, ry = HalfF(raw[1]) * H;
                        errFix.push_back(std::hypot(fx - ex, fy - ey));
                        errRaw.push_back(std::hypot(rx - ex, ry - ey));
                        mag.push_back(std::hypot(ex, ey));
                        sumFixX += fx;
                        sumFixY += fy;
                    }
                }
                auto pct = [](std::vector<double> v, double p) {
                    if (v.empty()) {
                        return 0.0;
                    }
                    std::sort(v.begin(), v.end());
                    return v[static_cast<std::size_t>(p * (v.size() - 1))];
                };
                REX::INFO("stereomvcheck: {} world samples, expected |mv| median {:.2f} px p95 {:.2f} | per-eye MV error median {:.3f} p95 {:.3f} "
                          "max {:.3f} px | mono (engine) MV error median {:.3f} p95 {:.3f} px | depth fmt {}",
                    errFix.size(), pct(mag, 0.5), pct(mag, 0.95), pct(errFix, 0.5), pct(errFix, 0.95), pct(errFix, 1.0), pct(errRaw, 0.5),
                    pct(errRaw, 0.95), static_cast<int>(g_mvCheck.depthFmt));
            } else {
                REX::WARN("stereomvcheck: map failed");
            }
            for (int i = 0; i < 3; ++i) {
                if (m[i].pData) {
                    g_ctx->Unmap(g_mvCheck.st[i], 0);
                }
            }
            g_mvCheck.state = 0;
        }

        void WriteStageCaptures()
        {
            std::string seen;
            for (int s = 0; s < kStages; ++s) {
                if (g_stageCap.seen[s] && g_stageCap.staging[s]) {
                    AnalyzeStage(g_stageCap.stem, s);
                    seen += std::string(" ") + kStageNames[s];
                }
                g_stageCap.seen[s] = false;
                g_stageCap.draws[s] = 0;
            }
            REX::INFO("stereostage: {} done (stages:{})", g_stageCap.stem, seen.empty() ? " none" : seen);
        }
