"""Generate plugin/src/plugin/StereoTargets.inl: the table the draw hook uses to recognise vertex shaders at
ID3D11Device::CreateVertexShader time, keyed by the 16-byte DXBC header checksum (blob bytes 4..20).

PROTOTYPE TOOL (stereo PoC). stdlib only. Run with:
  python -I plugin/proto/stereo/tools/gen_targets.py [Shaders011.fxp] [vs_pos.json] [out.inl]
Defaults point at the flat 1.11.240 extraction in work/shaders/flat.

Families (see analysis/stereo-poc-plan.md section 3):
  1 G008_PTNB   g008 (deferred GBuffer lighting) static, ISGN POSITION TEXCOORD NORMAL BINORMAL,
                position = cb12[8..11] * (World(cb2[0..3]) - PosAdjust(cb12[35]))
  2 G008_PTNBC  same + COLOR0
Flags:
  1 FAITHFUL  the blob is exactly the one transcribed in shaders/StereoVS.hlsl (engine PS can stay)
  2 DEBUG     same ISGN + same position math, no existing clip distance: the simplified VS + debug PS
              can replace it (the PS is replaced too, so the OSGN does not matter)
  4 GEOMETRY  material-group (0..11) VS whose position depends on a camera (category A or B);
              used by the "skip unconverted geometry" measurement mode
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'analysis', 'tools', 'shaders'))
import fxp  # noqa: E402

fxp_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'work', 'shaders', 'flat', 'ShadersFX', 'Shaders011.fxp')
pos_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'work', 'shaders', 'flat', 'vs_pos.json')
out_path = sys.argv[3] if len(sys.argv) > 3 else os.path.join(HERE, '..', '..', '..', 'src', 'plugin', 'StereoTargets.inl')

EXACT_POS = {'cb12': [8, 9, 10, 11, 35], 'cb2': [0, 1, 2, 3]}
ISGN_FAMILY = {
    ('POSITION0', 'TEXCOORD0', 'NORMAL0', 'BINORMAL0'): 1,
    ('POSITION0', 'TEXCOORD0', 'NORMAL0', 'BINORMAL0', 'COLOR0'): 2,
}
# The two blobs transcribed instruction by instruction into StereoVS.hlsl (FAITHFUL mode).
FAITHFUL_SHA1 = {
    1: '78f8f2be99',  # g008_vs_0100001a and 25 other technique ids
    2: 'd59ecb3a18',  # g008_vs_0100001b and 25 other technique ids
}

vp = {r['name']: r for r in json.load(open(pos_path))}
groups = fxp.parse_fxp(fxp_path)

import hashlib  # noqa: E402

rows = {}  # checksum hex -> dict
for gi, g in enumerate(groups):
    if gi > 11:
        continue
    for e in g['entries']:
        if e['stage'] != 'vs':
            continue
        name = 'g%03d_vs_%08x' % (gi, e['id'])
        r = vp[name]
        blob = e['blob']
        key = blob[4:20].hex()
        sha1 = hashlib.sha1(blob).hexdigest()
        sigs = fxp.signatures(blob)
        isgn = tuple('%s%d' % (s['name'], s['idx']) for s in sigs.get('ISGN', []))
        osgn_sv = [s['sv'] for s in sigs.get('OSGN', [])]
        pos = r['pos_cb']
        family, flags = 0, 0
        if pos and ('cb2' in pos or 'cb12' in pos or 'cb10' in pos or 'cb13' in pos):
            flags |= 4
        if (gi == 8 and pos == EXACT_POS and r['pos_inputs'] == ['v0'] and isgn in ISGN_FAMILY
                and 'CLIPDIST' not in osgn_sv and 'CULLDIST' not in osgn_sv):
            family = ISGN_FAMILY[isgn]
            flags |= 2
            if sha1.startswith(FAITHFUL_SHA1[family]):
                flags |= 1
        cur = rows.get(key)
        if cur is None:
            rows[key] = dict(key=key, family=family, flags=flags, name=name, n=1, sha1=sha1)
        else:
            assert cur['sha1'] == sha1, 'checksum collision'
            cur['n'] += 1

sel = sorted(rows.values(), key=lambda x: (-(x['flags'] & 3), x['name']))
nf = sum(1 for x in sel if x['flags'] & 1)
nd = sum(1 for x in sel if x['flags'] & 2)
ng = sum(1 for x in sel if x['flags'] & 4)
with open(out_path, 'w', newline='\n') as f:
    f.write('// GENERATED by plugin/proto/stereo/tools/gen_targets.py - do not edit. PROTOTYPE (unbuilt).\n')
    f.write('// Source: %s\n' % os.path.relpath(fxp_path, ROOT).replace('\\', '/'))
    f.write('// %d unique material-group VS blobs: %d FAITHFUL, %d DEBUG-convertible, %d camera-dependent geometry.\n'
            % (len(sel), nf, nd, ng))
    f.write('// { DXBC header checksum (blob[4..20]), family, flags, technique uses, example }\n')
    for x in sel:
        b = bytes.fromhex(x['key'])
        f.write('{ { %s }, %d, %d, %d },  // %s\n' % (
            ', '.join('0x%02X' % c for c in b), x['family'], x['flags'], x['n'], x['name']))
print('wrote', out_path, len(sel), 'rows; faithful', nf, 'debug', nd, 'geometry', ng)
